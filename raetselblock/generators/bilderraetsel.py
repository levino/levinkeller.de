def _pool_grid(rows):
    return [[1 if ch == "#" else 0 for ch in r] for r in rows]


def generate(level, rng):
    pool = POOLS[level]
    name = rng.choice(sorted(pool))
    rows = pool[name]
    g = _pool_grid(rows)
    rc, cc = grid_clues(g)
    return {
        "data": {"w": len(rows[0]), "h": len(rows), "rows": rc, "cols": cc},
        "solution": {"name": name, "grid": list(rows)},
    }


def count_solutions(data, limit=2):
    return count_sat(data["rows"], data["cols"], limit=limit)
